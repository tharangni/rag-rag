// Realistic synthetic candle generator for any asset and timeframe
export function generateCandles(basePrice: number, timeframe: Timeframe, count = 48): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  
  let stepMs = 5 * 60 * 1000; // 5 min default for 1D
  if (timeframe === '5D') stepMs = 30 * 60 * 1000;
  if (timeframe === '1M') stepMs = 4 * 60 * 60 * 1000;
  if (timeframe === '3M') stepMs = 24 * 60 * 60 * 1000;
  if (timeframe === '1Y') stepMs = 24 * 60 * 60 * 1000 * 3;
  if (timeframe === '5Y') stepMs = 7 * 24 * 60 * 60 * 1000 * 2;
  if (timeframe === 'ALL') stepMs = 30 * 24 * 60 * 60 * 1000;

  // Volatility percentage per candle
  const volPct = timeframe === '1D' ? 0.003 : timeframe === '5D' ? 0.007 : 0.015;
  
  // Seed starting price slightly earlier
  let current = basePrice * (1 - (volPct * count * 0.35));

  for (let i = count - 1; i >= 0; i--) {
    const timestamp = now - i * stepMs;
    const dateObj = new Date(timestamp);
    let timeLabel = '';

    if (timeframe === '1D') {
      timeLabel = dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    } else if (timeframe === '5D' || timeframe === '1M') {
      timeLabel = `${dateObj.getMonth() + 1}/${dateObj.getDate()} ${dateObj.getHours()}:00`;
    } else {
      timeLabel = dateObj.toLocaleDateString([], { month: 'short', day: 'numeric', year: timeframe === '5Y' || timeframe === 'ALL' ? '2-digit' : undefined });
    }

    const change = (Math.random() - 0.47) * volPct * current;
    const open = current;
    const close = i === 0 ? basePrice : current + change;
    const high = Math.max(open, close) + Math.random() * (volPct * 0.8) * current;
    const low = Math.min(open, close) - Math.random() * (volPct * 0.8) * current;
    const volume = Math.floor(Math.random() * 400000 + 100000);

    candles.push({
      time: timeLabel,
      timestamp,
      open: Number(open.toFixed(basePrice < 10 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 10 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 10 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 10 ? 4 : 2)),
      volume
    });

    current = close;
  }

  // Ensure last candle close is exactly basePrice
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
    candles[candles.length - 1].high = Math.max(candles[candles.length - 1].high, basePrice);
    candles[candles.length - 1].low = Math.min(candles[candles.length - 1].low, basePrice);
  }

  return candles;
}

